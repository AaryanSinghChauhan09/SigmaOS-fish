"""Shell configuration engine for SigmaOS-zsh / SigmaOS-fish
(inspired by omarchy-zsh and omarchy-fish).

Principles: generated files carry a managed block (idempotent re-merge, never
truncates user config), plan/execute separation (apply builds an argv plan and
only the thin executor writes -- self_test stays on strings and plans),
fail-fast on conflicting aliases, deterministic output ordering (sorted).
"""
import argparse, os, re, shlex, subprocess, sys

ENGINE = {
    "name": "sigma-shell",
    "summary": "Shell config generator: plugins, aliases, managed apply plan",
    "language": "python",
    "verbs": ["generate", "plugins", "aliases", "apply-plan"],
    "principles": ["Separation of Concerns", "Defensive Programming",
                   "Fail-Fast", "DRY", "KISS", "Deterministic Testing"],
}

cli_doc = """\
$ sigma-shell plugins plugins.txt
zsh-autosuggestions
zsh-syntax-highlighting
$ sigma-shell aliases aliases.txt
gs = git status
$ sigma-shell generate --shell zsh --plugins plugins.txt --alias gs='git status'
$ sigma-shell apply-plan --shell zsh --dest ~/.zshrc
"""

BEGIN_MARK = "# SIGMAOS-SHELL-BEGIN"
END_MARK = "# SIGMAOS-SHELL-END"
SHELLS = ("zsh", "fish")
_PLUGIN_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9._+-]*$")
_ALIAS_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")


class ShellError(ValueError):
    pass


def _iter_data_lines(text):
    if not isinstance(text, str):
        raise ShellError("expected text input")
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        yield s


def parse_plugins(text):
    """Ordered, de-duplicated plugin names; fail-fast on bad names."""
    out, seen = [], set()
    for line in _iter_data_lines(text):
        if " " in line:
            raise ShellError(f"plugin name must be a single token: {line!r}")
        if not _PLUGIN_RE.match(line):
            raise ShellError(f"invalid plugin name: {line!r}")
        if line not in seen:
            seen.add(line)
            out.append(line)
    return out


_ALIAS_RE = re.compile(r"^alias\s+([A-Za-z_][A-Za-z0-9_-]*)\s*=?\s*(.*)$")


def parse_aliases(text):
    """Parse `alias n='v'` (zsh/fish) and `alias n v` (fish) definitions."""
    aliases = {}
    for line in _iter_data_lines(text):
        m = _ALIAS_RE.match(line)
        if not m:
            raise ShellError(f"not an alias definition: {line!r}")
        name, value = m.group(1), m.group(2).strip()
        if value.startswith(("'", '"')):
            if len(value) < 2 or not value.endswith(value[0]):
                raise ShellError(f"unterminated quote in alias {name}")
            value = value[1:-1]
        if not value:
            raise ShellError(f"alias {name} has an empty value")
        if "\n" in value:
            raise ShellError(f"alias {name} value contains a newline")
        if name in aliases and aliases[name] != value:
            raise ShellError(
                f"conflicting alias {name}: {aliases[name]!r} vs {value!r}")
        aliases[name] = value
    return aliases


def render_plugins_block(shell, plugins):
    if shell not in SHELLS:
        raise ShellError(f"unknown shell {shell!r} (have: {', '.join(SHELLS)})")
    lines = [BEGIN_MARK + " plugins"]
    if shell == "zsh":
        for p in plugins:
            lines.append(f'plugin_path="/usr/share/zsh/plugins/{p}/{p}.zsh"')
            lines.append(f'[ -r "$plugin_path" ] && source "$plugin_path"')
    else:
        for p in plugins:
            lines.append(f'test -r /usr/share/fish/plugins/{p}.fish; '
                         f'and source /usr/share/fish/plugins/{p}.fish')
    lines.append(END_MARK)
    return "\n".join(lines)


def render_aliases_block(shell, aliases):
    if shell not in SHELLS:
        raise ShellError(f"unknown shell {shell!r}")
    lines = [BEGIN_MARK + " aliases"]
    for name in sorted(aliases):
        lines.append(f"alias {name}='{aliases[name]}'")
    lines.append(END_MARK)
    return "\n".join(lines)


def generate(shell, plugins=(), aliases=(), opts=True):
    """Full rc-file body with one managed block (sorted, deterministic)."""
    if shell not in SHELLS:
        raise ShellError(f"unknown shell {shell!r} (have: {', '.join(SHELLS)})")
    plugins = parse_plugins("\n".join(plugins)) if not isinstance(plugins, str) \
        else parse_plugins(plugins)
    if isinstance(aliases, str):
        aliases = parse_aliases(aliases)
    body = [
        f"# generated by sigma-shell ({shell}) -- edit inside the markers only",
        BEGIN_MARK,
    ]
    if shell == "zsh":
        body.append("setopt autocd sharehistory interactivecomments")
    else:
        body.append('set -g fish_greeting ""')
    if plugins:
        body += render_plugins_block(shell, plugins).splitlines()[1:-1]
    if aliases:
        body += render_aliases_block(shell, aliases).splitlines()[1:-1]
    body.append(END_MARK)
    if opts and shell == "zsh":
        body += ["", "export EDITOR=nvim", "alias ll='ls -lah'"]
    elif opts:
        body += ["", "set -gx EDITOR nvim", "alias ll='ls -lah'"]
    return "\n".join(body) + "\n"


def merge_managed_block(existing, block):
    """Replace (or append) the managed block inside `existing`. Idempotent."""
    if block.count(BEGIN_MARK) != 1 or END_MARK not in block:
        raise ShellError("block must contain exactly one begin marker and an end marker")
    out, skipping = [], False
    for line in (existing or "").splitlines():
        if line.strip().startswith(BEGIN_MARK):
            skipping = True
            continue
        if line.strip() == END_MARK:
            skipping = False
            continue
        if not skipping:
            out.append(line)
    out = [l for l in out if l.strip()]
    out.append(block)
    return "\n".join(out) + "\n"


def apply_plan(text, dest, exists=lambda p: False):
    """Pure plan: optional backup + write of generated text to `dest`."""
    if not isinstance(dest, str) or not dest.strip():
        raise ShellError("empty destination path")
    if "\n" in dest or "\x00" in dest:
        raise ShellError("destination must be a plain single path")
    if "\x00" in text:
        raise ShellError("generated text contains NUL")
    steps = []
    if exists(dest):
        steps.append({"kind": "backup", "argv": ["cp", "-a", dest, dest + ".bak"]})
    steps.append({"kind": "write", "path": dest, "content": text})
    return {"dest": dest, "steps": steps}


def execute(plan):
    """THIN side-effecting layer: backup (if planned) then write. Not self-tested."""
    for step in plan["steps"]:
        if step["kind"] == "backup":
            subprocess.run(step["argv"], check=True)
        else:
            with open(step["path"], "w", encoding="utf-8") as fh:
                fh.write(step["content"])


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog=ENGINE["name"], description=ENGINE["summary"])
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate", help="print a generated rc file")
    g.add_argument("--shell", default="zsh", choices=SHELLS)
    g.add_argument("--plugins", default=None, help="plugin list file")
    g.add_argument("--alias", action="append", default=[],
                   metavar="NAME=VALUE", help="alias (repeatable)")
    g.add_argument("--no-defaults", action="store_true")
    pl = sub.add_parser("plugins", help="parse & list a plugin list file")
    pl.add_argument("file")
    al = sub.add_parser("aliases", help="parse & list an alias file")
    al.add_argument("file")
    ap = sub.add_parser("apply-plan", help="build the backup/write plan")
    ap.add_argument("--shell", default="zsh", choices=SHELLS)
    ap.add_argument("--dest", required=True)
    ap.add_argument("--plugins", default=None)
    ap.add_argument("--alias", action="append", default=[], metavar="NAME=VALUE")
    ap.add_argument("--no-defaults", action="store_true")
    return p


def _read(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def _cli_aliases(pairs):
    out = {}
    for pair in pairs:
        if "=" not in pair:
            raise ShellError(f"--alias wants NAME=VALUE: {pair!r}")
        name, value = pair.split("=", 1)
        out.update(parse_aliases(f"alias {name}='{value}'"))
    return out


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.cmd == "plugins":
            for name in parse_plugins(_read(args.file)):
                print(name)
        elif args.cmd == "aliases":
            for name, value in sorted(parse_aliases(_read(args.file)).items()):
                print(f"{name} = {value}")
        elif args.cmd == "generate":
            text = generate(args.shell,
                            plugins=_read(args.plugins) if args.plugins else (),
                            aliases=_cli_aliases(args.alias),
                            opts=not args.no_defaults)
            print(text, end="")
        elif args.cmd == "apply-plan":
            text = generate(args.shell,
                            plugins=_read(args.plugins) if args.plugins else (),
                            aliases=_cli_aliases(args.alias),
                            opts=not args.no_defaults)
            plan = apply_plan(text, os.path.expanduser(args.dest),
                              exists=os.path.exists)
            for step in plan["steps"]:
                if step["kind"] == "backup":
                    print("backup " + shlex.join(step["argv"]))
                else:
                    print(f"write {step['path']} ({len(step['content'])} bytes)")
        return 0
    except (ShellError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


def self_test() -> None:
    # --- plugin list parsing ------------------------------------------------
    plugins = parse_plugins("# omarchy plugins\nzsh-autosuggestions\n"
                            "zsh-syntax-highlighting\n\nzsh-autosuggestions\n")
    assert plugins == ["zsh-autosuggestions", "zsh-syntax-highlighting"], plugins
    for bad in ("bad name\n", "rm -rf /\n", ";\n"):
        try:
            parse_plugins(bad)
        except ShellError:
            pass
        else:
            raise AssertionError(f"plugin should have been rejected: {bad!r}")

    # --- alias parsing (zsh + fish syntax) ----------------------------------
    a = parse_aliases("alias gs='git status'\nalias ll=ls -lah\n"
                      "alias k kubectl\n# comment\n")
    assert a == {"gs": "git status", "ll": "ls -lah", "k": "kubectl"}, a
    try:
        parse_aliases("alias gs='git status'\nalias gs='git stash'\n")
    except ShellError:
        pass
    else:
        raise AssertionError("conflicting alias not caught")
    for bad in ("not an alias\n", "alias =\n", "alias ok='unterminated\n"):
        try:
            parse_aliases(bad)
        except ShellError:
            pass
        else:
            raise AssertionError(f"alias should have been rejected: {bad!r}")

    # --- generation (deterministic, one managed block) ----------------------
    zsh = generate("zsh", plugins=plugins,
                   aliases={"gs": "git status", "ll": "ls -lah"})
    assert zsh.count(BEGIN_MARK) == 1 and zsh.count(END_MARK) == 1
    assert "setopt autocd" in zsh
    assert 'alias gs=\'git status\'' in zsh
    assert 'alias ll=\'ls -lah\'' in zsh
    assert "zsh-autosuggestions" in zsh
    assert zsh == generate("zsh", plugins=plugins,
                           aliases={"ll": "ls -lah", "gs": "git status"})
    fish = generate("fish", plugins=plugins, aliases={"k": "kubectl"})
    assert "set -g fish_greeting" in fish and "fish/plugins" in fish
    assert 'alias k=\'kubectl\'' in fish
    assert "setopt" not in fish
    try:
        generate("bash", plugins=())
    except ShellError:
        pass
    else:
        raise AssertionError("unknown shell not rejected")

    # --- managed-block merge is idempotent ---------------------------------
    block = render_plugins_block("zsh", ["zsh-autosuggestions"])
    merged = merge_managed_block("export EDITOR=vim\n", block)
    assert merged.count(BEGIN_MARK) == 1 and "export EDITOR=vim" in merged
    merged2 = merge_managed_block(merged, block)
    assert merged2.count(BEGIN_MARK) == 1
    assert merged2 == merged
    newer = render_plugins_block("zsh", ["zsh-syntax-highlighting"])
    merged3 = merge_managed_block(merged2, newer)
    assert "zsh-syntax-highlighting" in merged3
    assert "zsh-autosuggestions" not in merged3  # replaced, not appended
    assert merged3.count(BEGIN_MARK) == 1
    try:
        merge_managed_block("x", "no markers here")
    except ShellError:
        pass
    else:
        raise AssertionError("bad block not rejected")

    # --- apply plan (pure: injected existence predicate) --------------------
    plan = apply_plan(zsh, "/home/u/.zshrc", exists=lambda p: True)
    assert plan["steps"][0]["kind"] == "backup"
    assert plan["steps"][0]["argv"] == ["cp", "-a", "/home/u/.zshrc",
                                        "/home/u/.zshrc.bak"]
    assert plan["steps"][1] == {"kind": "write", "path": "/home/u/.zshrc",
                                "content": zsh}
    fresh = apply_plan(zsh, "/home/u/.zshrc", exists=lambda p: False)
    assert [s["kind"] for s in fresh["steps"]] == ["write"]
    for bad_call in ((apply_plan, ("x", "  ")), (apply_plan, ("x", "a\nb")),
                     (apply_plan, ("x\x00y", "/tmp/rc"))):
        try:
            bad_call[0](*bad_call[1])
        except ShellError:
            pass
        else:
            raise AssertionError(f"should have rejected: {bad_call}")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
